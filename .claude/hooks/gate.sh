#!/bin/sh
# Запуск гейта (SPEC.md, G3). Claude Code блокирует действие только по коду 2, любой другой код — «пропустить».
# Поэтому всё, кроме 0 и 2, превращается в 2: нет python3 или гейт упал до своего try — стоп, а не пропуск.
# Только встроенные команды sh: при пустом PATH обёртка должна дойти до своего сообщения.
gate="$1"
case "$0" in */*) dir="${0%/*}" ;; *) dir=. ;; esac
if ! command -v python3 >/dev/null 2>&1; then
  echo "$gate: python3 не найден в PATH — гейт не может проверить действие, оно остановлено. Установи Python 3 или добавь его в PATH." >&2
  exit 2
fi
python3 "$dir/$gate.py"
code=$?
if [ "$code" -ne 0 ] && [ "$code" -ne 2 ]; then
  echo "$gate: гейт завершился с кодом $code — действие остановлено." >&2
  exit 2
fi
exit "$code"
